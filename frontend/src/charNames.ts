// What people call a mark that Unicode names otherwise.
const ALIASES: Record<string, string> = { diaeresis: 'umlaut' }

function nameWords(c: string): string[] {
  const words = (CHAR_NAMES[paletteKey(c)] ?? '').split(' ')
  return [...words, ...words.flatMap((w) => ALIASES[w] ?? [])]
}

/** Whether `c` is what was searched for: the character itself, in either form, or one
 *  whose name holds each word searched - "long s", "a macron". The last word may still
 *  be being typed, so it only has to start one. */
export function matchesSearch(c: string, search: string): boolean {
  const asked = search.trim()
  if (paletteKey(c) === paletteKey(asked)) return true
  const words = nameWords(c)
  const typed = asked.toLowerCase().split(/\s+/)
  const typing = typed.pop()!
  return typed.every((a) => words.includes(a)) && words.some((w) => w.startsWith(typing))
}
